export const icons=iconCatalog.map(item=>{
  const shape=shapes[item.id];
  if(!shape)throw new Error('Missing custom shape: '+item.id);
  return {...item,...shape};
});
export function iconSvg(id,{size=24,filled=false,label,className=''}={}){
  const item=icons.find(item=>item.id===id);
  if(!item)throw new Error('Unknown icon: '+id);
  const solid=filled&&!!item.filled;
  return '<svg xmlns="http://www.w3.org/2000/svg" width="'+size+'" height="'+size+'" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" class="'+className+'" '+(label?'role="img" aria-label="'+item.label+'"':'aria-hidden="true"')+'>'+(solid?item.filled:item.body)+'</svg>';
}
